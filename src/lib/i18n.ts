let currentLang: Language = "en";

export function setLanguage(lang: Language) {
  currentLang = lang;
}

export function getLanguage(): Language {
  return currentLang;
}

export function t(key: string, sw: string, en: string): string {
  const entry = translations[key];
  if (entry) {
    return currentLang === "sw" ? entry.sw : entry.en;
  }
  return currentLang === "sw" ? sw : en;
}

export function translate(key: string, fallbackSw?: string, fallbackEn?: string): string {
  const entry = translations[key];
  if (entry) {
    return currentLang === "sw" ? entry.sw : entry.en;
  }
  if (fallbackSw && fallbackEn) {
    return currentLang === "sw" ? fallbackSw : fallbackEn;
  }
  if (fallbackEn) return fallbackEn;
  return key;
}
